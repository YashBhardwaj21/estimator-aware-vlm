"""Dataset Adapter protocols, trajectory models, and configuration.

Provides a dataset-agnostic abstraction layer with strict trajectory role separation
to ensure ground-truth poses cannot leak into perception, estimation, or routing.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from pathlib import Path
from typing import Iterator, List, Optional, Protocol, Tuple, Union, runtime_checkable
import numpy as np

