def save_table(
    table_id: str,
    title: str,
    headers: List[str],
    rows: List[List[Any]],
    out_dirs: List[Path],
    latex_column_align: Optional[str] = None,
    note: Optional[str] = None,
):
    """Save table in CSV, Markdown, and LaTeX formats."""
    for out_dir in out_dirs:
        out_dir.mkdir(parents=True, exist_ok=True)

        # 1. CSV
        csv_path = out_dir / f"{table_id}.csv"
        with open(csv_path, "w", newline="", encoding="utf-8") as f:
            writer = csv.writer(f)
            writer.writerow(headers)
            for row in rows:
                writer.writerow(row)

        # 2. Markdown
        md_path = out_dir / f"{table_id}.md"
        with open(md_path, "w", encoding="utf-8") as f:
            f.write(f"### {table_id.replace('_', ' ').title()}: {title}\n\n")
            f.write("| " + " | ".join(headers) + " |\n")
            f.write("| " + " | ".join([":---" if i == 0 else ":---:" for i in range(len(headers))]) + " |\n")
            for row in rows:
                f.write("| " + " | ".join(str(c) for c in row) + " |\n")
            if note:
                f.write(f"\n*{note}*\n")

        # 3. LaTeX
        tex_path = out_dir / f"{table_id}.tex"
        col_align = latex_column_align or ("l" + "c" * (len(headers) - 1))
        with open(tex_path, "w", encoding="utf-8") as f:
            f.write("% Auto-generated by generate_research_tables.py\n")
            f.write("\\begin{table}[htbp]\n")
            f.write("\\centering\n")
            f.write(f"\\caption{{{title}}}\n")
            f.write(f"\\label{{tab:{table_id}}}\n")
            f.write(f"\\begin{{tabular}}{{{col_align}}}\n")
            f.write("\\hline\n")
            f.write(" & ".join([f"\\textbf{{{h}}}" for h in headers]) + " \\\\\n")
            f.write("\\hline\n")
            for row in rows:
                clean_row = [str(c).replace("%", "\\%").replace("_", "\\_").replace("&", "\\&") for c in row]
                f.write(" & ".join(clean_row) + " \\\\\n")
            f.write("\\hline\n")
            f.write("\\end{tabular}\n")
            if note:
                clean_note = note.replace("%", "\\%").replace("_", "\\_")
                f.write(f"\\vskip 2pt \\footnotesize{{{clean_note}}}\n")
            f.write("\\end{table}\n")


